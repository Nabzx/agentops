"""Runs security_benchmark.py's suite and writes docs/security-benchmark.md.

Run from the repo root:

    cd ephor && uv run python -m tests.generate_security_benchmark_report
"""

from __future__ import annotations

import asyncio
from collections.abc import Sequence
from pathlib import Path

from tests.security_benchmark import BenchmarkCase, CaseResult, run_all

REPORT_PATH = Path(__file__).resolve().parents[2] / "docs" / "security-benchmark.md"

CATEGORY_ORDER = ["access-control", "audit-integrity", "exactly-once", "idempotency"]


async def _main() -> None:
    results = await run_all()

    defended = [(c, r) for c, r in results if c.kind == "defended"]
    limitations = [(c, r) for c, r in results if c.kind == "known_limitation"]
    stale = [(c, r) for c, r in results if not r.passed]

    def rows(pairs: Sequence[tuple[BenchmarkCase, CaseResult]]) -> str:
        lines = []
        for case, result in pairs:
            mark = "✓" if result.passed else "✗ STALE"
            lines.append(
                f"| `{case.name}` | {case.category} | {mark} | {result.detail} |"
            )
        return "\n".join(lines)

    headline = (
        "Every case matches its write-up."
        if not stale
        else ("Some cases are stale - see below.")
    )

    report = f"""# Ephor security benchmark

Generated by `ephor/tests/generate_security_benchmark_report.py` - a named, scored
suite of adversarial scenarios, not more unit tests in disguise. Each case either
**defends** (the core structurally blocks or detects the attack) or is an honest
**known limitation** (a trust boundary this core does not, and cannot, police -
demonstrated, not hidden). See `security_benchmark.py`'s module docstring and
`test_security_benchmark.py`, which asserts every case still matches what it claims
on every CI run. Regenerate this file by re-running the script - it isn't hand-edited.

## Result

| | |
| --- | --- |
| Cases run | {len(results)} |
| Defended | {len(defended)} |
| Known limitations (honestly demonstrated) | {len(limitations)} |
| Stale (no longer match their write-up) | **{len(stale)}** |

{headline}

## Defended

What the core structurally blocks or detects, demonstrated, not asserted from a
design document.

| Case | Category | Result | Detail |
| --- | --- | --- | --- |
{rows(defended)}

## Known limitations

Real, honest gaps - trust boundaries this core does not police, or a reference
implementation's shortcut against a stronger production guarantee. Demonstrated here
so nobody has to discover them the hard way.

| Case | Category | Result | Detail |
| --- | --- | --- | --- |
{rows(limitations)}

## Stale cases

{"None." if not stale else chr(10).join(f"- `{c.name}`: {r.detail}" for c, r in stale)}
"""

    REPORT_PATH.write_text(report)
    print(f"wrote {REPORT_PATH} ({len(stale)} stale)")


if __name__ == "__main__":
    asyncio.run(_main())
